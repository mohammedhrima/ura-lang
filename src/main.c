Node *parse_prime() {
    Token *token = next();
    Node *node = NULL;
    switch (token->type) { // clang-format off
    case I32: case I8: case BOOL: case CHARS: { // clang-format on
        if (token->name == NULL) {
            node = new_node(new_token(VAL_CREATE, token));
            node->left = new_node(token);
            return node;
        }
        return new_node(token);
    }
    case TEMPLATE: {
        node = new_node(token);
        if (!check_next(LT, "expected <", "<"))
            return recover(token);
        next(); // skip <
        while (!includes(peek(0)->type, GT, END, 0)) {
            Node *type = parse_prime();
            if (type->token->type != ID) {
                eprint("expected ID\n");
                return recover(type->token);
            }
            // TODO: check this one
            if (peek(0)->type == COMA)
                next();
            type->token->type = TEMPLATE_TYPE;
            push_back(node->children, type);
        }

        if (!check_next(GT, "expected >", ">"))
            return recover(peek(0));
        next(); // skip >

        if (!check_next(DOTS, "expected :", ":"))
            return recover(peek(0));
        next(); // skip :

        enter_scope(node);
        while (inside(token->space)) {
            Node *child = parse_prime();
            push_child(node, child);
        }
        exit_scope();
        // print("%n", node);
        // exit(1);
        return node;
    }
    case STRUCT: {
        for (int i = 0; i < ura.scope->children_count; i++) {
            Token *scope_token = ura.scope->children[i]->token;
            if (scope_token == token) {
                node = ura.scope->children[i];
                break;
            }
        }
        if (node == NULL) { // TODO: use recover
            eprint("undeclared struct %s\n", token->name);
            exit(1);
        }
        next(); // skip ID
        next(); // skip :

        enter_scope(node);
        while (inside(node->token->space)) {
            Node *attr = parse_prime();
            Type type = attr->token->type;
            // TODO: should be declaration, or FN_DEC
            push_back(node->children, attr);
        }
        exit_scope();
        return node;
    }
    case LBRACK: {
        token->type = ARRAY_LIT;
        node = new_node(token);
        while (peek(0)->type != RBRACK) {
            push_back(node->children, parse_expr(0));
            if (peek(0)->type != COMA)
                break;
            next();
        }
        if (!check_next(RBRACK, "expected ']' to close this '['", "]"))
            return recover(token);
        next(); // skip ]
        return node;
    }
    case ID: {
        Node *type = parse_type();
        if (type) {
            node = new_node(new_token(DECLARE, token));
            node->left = new_node(token);
            node->left->left = type;
            return node;
        }
        if (peek(0)->type == LPARENT) { // FN_CALL
            token->type = FN_CALL;
            node = new_node(token);
            next(); // skip (
            node->right = new_node(new_token(ARGS, token));
            while (peek(0)->type != RPARENT) {
                push_back(node->right->children, parse_expr(0));
                if (peek(0)->type != COMA)
                    break;
                next(); // skip ,
            }
            char *msg = format("expected ')' to close the call to '%s'", token->name);
            if (!check_next(RPARENT, msg, ")"))
                return recover(token);
            next(); // skip )
            return node;
        }
        Token *after = peek(0);
        // p Point: no type named Point
        if (after->type == ID && after->line == token->line) {
            next();
            error((Error){
                .token = after,
                .msg = format("unknown type '%s'", after->name),
                .help = format("declare it: struct %s:", after->name),
            });
            return new_node(token);
        }
        // if (peek(0)->type == LBRACK) {
        //     node = new_node(token);
        //     while (peek(0)->type == LBRACK) {
        //         Node *access = new_node(next()); // skip [
        //         access->token->type = ACCESS;
        //         access->left = node;
        //         access->right = parse_expr(0);
        //         if (peek(0)->type != RBRACK) {
        //             eprint("expected ]\n");
        //             exit(1);
        //         }
        //         next();
        //         node = new_node(new_token(LOAD, access->token));
        //         node->token->name = "item";
        //         node->left = access;
        //     }
        //     return node;
        // }

        return new_node(token);
    }
    case REF: {
        // token->type = OWN;
        node = new_node(token);
        // fix for &p.next
        // to capture &(p.next) instead of (&p).next
        node->left = parse_expr(precedence[AS]);
        assert(node->left);
        // assert(node->left->token->type == ID);
        return node;
    } // clang-format off
    case FN_DEC: case PROTO: { // clang-format on
        node = new_node(token);
        token = next();
        if (token->type != ID) {
            error((Error){
                .token = token,
                .msg = format("expected a name after '%s'", token_text(node->token)),
                .help = fix_line(token->s, 0, "name"),
            });
            return recover(node->token);
        }
        node->token->name = token->name;
        node->token->s = token->s; // errors point at the name, not at 'fn'
        node->token->e = token->e;
        Node *struct_node = NULL;
        if (node->token->type == FN_DEC && ura.scope->token->type == STRUCT) {
            struct_node = ura.scope;
        }

        if (!check_next(LPARENT, "expected '(' after the function name", "()"))
            return recover(token);
        next(); // skip (

        node->right = new_node(new_token(ARGS, token));
        if (struct_node != NULL) {
            Token *self = new_token(ID, token);
            self->name = "self";
            Node *type = new_node(new_token(REF, token));
            type->left = struct_node;
            add_param(node, self, type);
        }

        while (peek(0)->type != RPARENT) {
            if (peek(0)->type == VARIADIC) {
                next();
                node->token->is_variadic = true;
                if (!check_next(RPARENT, "... must be the last parameter", NULL))
                    return recover(token);
                break;
            }
            Token *id = next();
            if (id->type != ID) {
                error((Error){ .token = id, .msg = "expected a parameter name" });
                return recover(token);
            }
            Node *type = parse_type();
            if (!type) {
                error((Error){
                    .token = id,
                    .msg = format("parameter '%s' has no type", id->name),
                    .help = fix_line(id->e, 0, " i32"),
                });
                return recover(token);
            }
            add_param(node, id, type);
            if (peek(0)->type != COMA)
                break;
            next(); // skip ,
        }

        if (!check_next(RPARENT, "expected ')' after the parameters", ")"))
            return recover(token);
        next(); // skip )

        Node *type = parse_type();
        // if (!check_next(I32, "expected i32")) // TODO: expect data type
        //     return recover(token);
        if (type)
            node->left = type;
        else
            node->left = new_node(new_token(VOID, token));

        if (node->token->type != PROTO) {
            if (!check_next(DOTS, "expected ':' after the function header", ":"))
                return recover(token);
            next();
            enter_scope(node);
            parse_body(node);
            push_back(node->children, get_default_return(node));
            exit_scope();
        }

        return node;
    }
    case RETURN: {
        node = new_node(token);
        // TODO: we need to make sure it's on same space
        if (peek(0)->space == token->space)
            node->left = parse_expr(0);
        return node;
    }
    case IF: {
        // a scope is entered only for a body: a broken header returns with none to
        // leave
        node = new_node(token);
        node->left = parse_expr(0);
        if (!check_next(DOTS, "expected ':' after the if condition", ":"))
            return recover(token);
        next();
        enter_scope(node);
        parse_body(node);
        exit_scope();

        Node *curr = node;
        while (inside(node->token->space - 1)) {
            Token *next_token = peek(0);
            if (!includes(next_token->type, ELIF, ELSE, 0))
                break;

            curr->right = new_node(next());
            curr = curr->right;
            Token *word = curr->token;
            if (word->type == ELIF)
                curr->left = parse_expr(0);
            else if (peek(0)->type != DOTS) { // else x > 1:
                error((Error){
                    .token = word,
                    .msg = "else has no condition",
                    .help = fix_line(word->s, word->e - word->s, "elif"),
                });
                return recover(word); // skip the rest of its line
            }
            char *arg = word->type == ELIF ? "the elif condition" : "else";
            char *msg = format("expected ':' after %s", arg);
            if (!check_next(DOTS, msg, ":"))
                return recover(word);
            next();
            enter_scope(curr);
            parse_body(curr);
            exit_scope();
        }
        return node;
    } // clang-format off
    case ELIF: case ELSE: { // clang-format on
        char *help = NULL;
        if (token->type == ELIF)
            help = fix_line(token->s, token->e - token->s, "if");
        error((Error){
            .token = token,
            .msg = format("%s without an if before it", token_text(token)),
            .help = help,
        });
        return recover(token);
    }
    case WHILE: {
        node = new_node(token);
        node->left = parse_expr(0);
        if (!check_next(DOTS, "expected ':' after the while condition", ":"))
            return recover(token);
        next();
        enter_scope(node);
        parse_body(node);
        exit_scope();
        return node;
    } // clang-format off
    case BRK: case CNT: { // clang-format on
        // TODO: when declaring function inside function this might cause problem
        node = new_node(token);
        for (int i = ura.scopes_count - 1; i > 0 && !node->left; i--) {
            if (ura.scopes[i]->token->type == WHILE)
                node->left = ura.scopes[i];
        }
        if (node->left == NULL) {
            char *word = token_text(token);
            error((Error){
                .token = token,
                .msg = format("%s outside a loop", word),
                .help = format("%s only works inside a while", word),
            });
        }
        // assert_inside_loop(node);
        return node;
    }
    case NOT: {
        node = new_node(token);
        node->left = parse_expr(precedence[AND]);
        return node;
    }
    case SCOPE: {
        // if (parent != NULL) {
        // }
        return new_node(token);
    }
    case LPARENT: {
        node = parse_expr(0);
        if (!check_next(RPARENT, "expected ')' to close this '('", ")"))
            return recover(token);
        next(); // skip )
        return node;
    }
    case SUB: {
        node = parse_prime();
        Node *tmp = new_node(new_token(SUB, token));
        tmp->left = new_node(new_token(VAL_CREATE, token));
        tmp->left->left = new_node(new_token(I32, token));
        tmp->right = node;
        node = tmp;
        return node;
    }
    case TYPES:
    case TEMPLATE_TYPE: {
        raise(SIGSEGV);
        break;
    }
    default:
        print("%k\n", peek(-2));
        eprint("handle this case %k\n", token);
        exit(1);
        break;
    }
    return NULL;
}

Node *parse_expr(int min_op) {
    Node *left = parse_prime();
    if (left->token->type == SCOPE) {
        enter_scope(left);
        while (inside(left->token->space)) {
            Node *child = parse_expr(0);
            assert(child != NULL);
            Type type = child->token->type;
            switch (type) {
            case TEMPLATE:
            case STRUCT: {
                push_back(left->children, child);
                break;
            }
            case FN_DEC: {
                push_back(left->children, child);
                break;
            }
            default: {
                push_back(left->children, child);
                break;
            }
            }
        }
        exit_scope();
        return left;
    }
    while (true) {
        if (peek(0)->type == LBRACK) {
            left = parse_access(left);
            continue;
        }

        int op = precedence[peek(0)->type];
        // assert(op != 0);
        if (op <= min_op)
            break;
        Node *node = new_node(next());
        node->left = left;

        Token *after = peek(0);
        if (after->type == END || after->line != node->token->line) {
            error((Error){
                .token = node->token,
                .msg = format("expected a value after '%s'", token_text(node->token)),
            });
            return recover(node->token);
        }

        if (node->token->type == DOT) {
            node->right = parse_prime();
            if (node->right->token->type != FN_CALL) {
                char *lname = node->left->token->name;
                char *rname = node->right->token->name;
                char *name = format("%s.%s", lname, rname);
                node->token->name = name;
                Node *load = new_node(new_token(LOAD, node->token));
                load->token->name = name;
                load->left = node;
                node = load;
            } else {
                // check later on
            }
        } else if (node->token->type == AS) {
            node->right = parse_type();
            if (node->right == NULL) {
                eprint("expected a type after 'as'\n");
                exit(1);
            }
        } else
            node->right = parse_expr(op);

        left = node;
    }
    return left;
}

Node *find_variable(char *name) {
    // print("search for %s\n", name);
    for (int i = ura.scopes_count; i > 0; i--) {
        Node *scope = ura.scopes[i - 1];
        // print(CYAN("in scope %s\n"), scope->token->name);

        for (int j = 0; j < scope->children_count; j++) {
            Node *child = scope->children[j];
            if (child->token->type != DECLARE)
                continue;
            Node *var = child->left;
            if (var->token->type != VAR)
                continue;
            assert(var);
            assert(var->token);
            // assert(name);
            if (ura_cmp(var->token->name, name))
                return var;
        }
    }
    return NULL;
}

Node *find_function(Node *call) {
    char *name = call->token->name;
    for (int i = ura.scopes_count; i > 0; i--) {
        Node *scope = ura.scopes[i - 1];
        assert(scope != NULL);
        for (int j = 0; j < scope->children_count; j++) {
            Node *child = scope->children[j];
            if (!includes(child->token->type, FN_DEC, PROTO, 0))
                continue;
            // print("====================\n");
            // print("%n", child);
            if (ura_cmp(child->token->name, name) && same_params(child, call))
                return child;
        }
    }
    no_function(call);
    exit(1);
    return NULL;
}

Node *find_attribute(Node *node, Node *struct_node, Node *attr) {
    char *str0 = node->left->token->name;
    char *str1 = node->right->token->name;
    int index = 0;
    for (int i = 0; i < struct_node->children_count; i++) {
        Node *child = struct_node->children[i];
        if (child->token->type != DECLARE)
            continue;
        child = child->left; // VAR
        if (ura_cmp(attr->token->name, child->token->name)) {
            node->token->name = format("%s.%s", str0, str1);
            node->token->attr.index = index;
            return child;
        }
        index++;
    }
    char *names = NULL; // the attributes it has
    for (size_t i = 0; i < struct_node->children_count; i++) {
        Node *child = struct_node->children[i];
        if (child->token->type != DECLARE)
            continue;
        char *name = child->left->token->name;
        names = names ? format("%s, %s", names, name) : name;
    }
    char *sname = struct_node->token->name;
    error((Error){
        .token = attr->token,
        .msg = format("%s has no attribute '%s'", sname, str1),
        .help = names ? format("%s has: %s", sname, names) : NULL,
    });
    return NULL;
}

Node *find_method(Node *caller, Node *struct_node, Node *method) {
    // print("========================\n");
    // print("%d %n", LINE, caller);
    // print("%d %n", LINE, struct_node);
    // print("%d %n", LINE, method);
    // print("========================\n");

    Node **args0 = method->right->children;
    int args_count0 = method->right->children_count;
    Node **args1 = ura_alloc(args_count0 + 1, sizeof(Node *));
    memcpy(args1 + 1, args0, args_count0 * sizeof(Node *));
    // TODO: to be cheked later on, wyh analyze_type worked here
    if (analyze_type(caller)->token->type != REF) {
        Node *ref = new_node(new_token(REF, caller->token));
        ref->left = caller;
        caller = ref;
    }
    args1[0] = caller;
    method->right->children = args1;
    method->right->children_count = args_count0 + 1;

    for (int i = 0; i < struct_node->children_count; i++) {
        Node *child = struct_node->children[i];
        if (child->token->type != FN_DEC)
            continue;
        if (!ura_cmp(child->token->name, method->token->name))
            continue;
        if (!same_params(child, method))
            continue;
        return child;
    }
    char *names = NULL; // the methods it has, each name once (overloads share one)
    for (size_t i = 0; i < struct_node->children_count; i++) {
        Node *child = struct_node->children[i];
        if (child->token->type != FN_DEC)
            continue;
        bool seen = false;
        for (size_t j = 0; j < i; j++) {
            Node *before = struct_node->children[j];
            // TODO: check this bullshit
            seen |= before->token->type == FN_DEC &&
                    ura_cmp(before->token->name, child->token->name);
        }
        if (!seen)
            names = names ? format("%s, %s", names, child->token->name)
                          : child->token->name;
    }
    char *sname = struct_node->token->name;
    error((Error){
        .token = method->token,
        .msg = format("%s has no method '%s'", sname, method->token->name),
        .help = names ? format("%s has: %s", sname, names) : NULL,
    });
    return NULL;
}

bool same_type(Node *left, Node *right) {
    if (left->token->type != right->token->type)
        return false;
    if (left->token->type == STRUCT)
        return ura_cmp(left->token->name, right->token->name);
    if (includes(left->token->type, REF, ARRAY, 0))
        return same_type(left->left, right->left);
    return true;
}

bool same_params(Node *fdec, Node *other) {
    Node *params = fdec->right;
    Node *items = other->right;
    int want = params->children_count;
    int got = items->children_count;
    if (fdec->token->is_variadic ? got < want : got != want)
        return false;
    for (int i = 0; i < want; i++) {
        Node *ptype = analyze_type(params->children[i]);
        Node *otype = analyze_type(items->children[i]);
        if (!same_type(ptype, otype))
            return false;
    }
    return true;
}

void analyze_function(Node *node) {
    for (int i = 0; i < ura.scope->children_count; i++) {
        Node *dec = ura.scope->children[i];
        if (!includes(dec->token->type, FN_DEC, PROTO, 0))
            continue;
        if (dec == node)
            break; // only the ones before it
        if (!same_params(dec, node))
            continue;
        if (ura_cmp(dec->token->name, node->token->name)) {
            char *name = node->token->name;
            int line = dec->token->line + 1; // clang-format off
            char *msg = format("function '%s' is already declared, on line %d", name, line);
            // clang-format on
            error((Error){
                .token = node->token,
                .msg = msg,
            });
            exit(1);
        }
    }
    char *name = NULL;
    if (ura.scope->token->type == STRUCT)
        name = format("%s.%s", ura.scope->token->name, node->token->name);
    else
        name = node->token->name;
    node->token->llvm.name = name;
}

void analyze_struct(Node *node) {
    for (int i = 0; i < ura.scope->children_count; i++) {
        Node *dec = ura.scope->children[i];
        if (!includes(dec->token->type, STRUCT, 0))
            continue;
        if (dec == node)
            break; // only the ones before it
        if (ura_cmp(dec->token->name, node->token->name)) {
            char *name = node->token->name;
            int line = dec->token->line + 1; // clang-format off
            char *msg = format("struct '%s' is already declared, on line %d", name, line);
            // clang-format on
            error((Error){
                .token = node->token,
                .msg = msg,
            });
            exit(1);
        }
    }
}

void analyze_body(Node *node) {
    for (int i = 0; i < node->children_count; i++) {
        Node *child = node->children[i];
        node->children[i] = analyze(child, 1);
    }
}

Node *analyze_type(Node *node) {
    switch (node->token->type) {
    case LOAD: {
        return analyze_type(node->left);
    } // clang-format off
    case VAR: case ARG: { // left is the data type
        return node->left;
    }
    case ZERO: {
        return node->left;
    }
    case I32: case I8: case BOOL: {
        return node;
    } // clang-format on
    case VAL_CREATE: {
        return analyze_type(node->left);
    }
    case DOT: {
        return analyze_type(node->right);
    }
    case DREF: {
        return analyze_type(node->left)->left;
    }
    case REF: {
        Node *ref = new_node(new_token(REF, node->token));
        ref->left = analyze_type(node->left);
        return ref;
    }
    case CHARS: {
        Node *array = new_node(new_token(ARRAY, node->token));
        array->left = new_node(new_token(I8, node->token));
        return array;
    }
    case AS: {
        return node->right;
    }
    case FN_CALL: {
        return node->left->left;
    }
    case ACCESS: {
        return analyze_type(node->left)->left;
    }
    // TODO: to be reviewed
    // clang-format off
    case EQ: case NQ: case LT: case GT: case LE: case GE:
    case AND: case OR: case NOT: case IS_NULLABLE:
        return new_node(new_token(BOOL, node->token));
    case ADD: case SUB: case MUL: case DIV: case MOD:
        return analyze_type(node->left); // clang-format on
    default: {
        eprint("handle this case %k\n", node->token);
        exit(1);
    }
    }
    return NULL;
}

char *ura_text(Node *node) {
    // clang-format off
    char *ops[END + 1] = {
        [ADD] = "+", [SUB] = "-", [MUL] = "*", 
        [DIV] = "/", [MOD] = "%",
        
        [ADD_ASSIGN] = "+", [SUB_ASSIGN] = "-", 
        [MUL_ASSIGN] = "*", [DIV_ASSIGN] = "/", 
        [MOD_ASSIGN] = "%",
        
        [EQ] = "==", [NQ] = "!=", 
        [LT] = "<", [GT] = ">", 
        [LE] = "<=", [GE] = ">=",
        
        [AND] = "and", [OR] = "or",
    };
    // clang-format on
    Token *token = node->token;
    if (ops[token->type]) {
        char *ltext = ura_text(node->left);
        char *rtext = ura_text(node->right);
        char *optext = ops[token->type];
        return format("%s %s %s", ltext, optext, rtext);
    }
    switch (token->type) { // clang-format off
    case VAR: case ARG: case ID: // clang-format on
        return token->name;
    case VAL_CREATE:
        return ura_text(node->left);
    case LOAD:
        return format("load.%s", ura_text(node->left));
    case DREF:
        return format("dref.%s", ura_text(node->left));
    case I32:
        return format("%d", token->i32.value);
    case I8:
        return format("'%c'", token->i8.value);
    case BOOL:
        return token->b1.value ? "True" : "False";
    case CHARS:
        return "str";
    case REF:
        return format("&%s", ura_text(node->left));
    case ACCESS:
        return format("%s[%s]", ura_text(node->left), ura_text(node->right));
    case DOT:
        return format("%s.%s", ura_text(node->left), node->right->token->name);
    case AS:
        return format("(%N)%s", node->right, ura_text(node->left));
    // case NEG: return format("-%s", ura_text(node->left));
    case FN_CALL: {
        char *text = format("%s(", token->name);
        Node *right = node->right;
        for (int i = 0; i < right->children_count; i++) {
            Node *child = right->children[i];
            text = format("%s%s%s", text, i == 0 ? "" : ",", ura_text(child));
        }
        return format("%s)", text);
    }
    default:
        break;
    }
    return (char *)to_string(token->type);
}

Node *analyze(Node *node, bool load) {
    switch (node->token->type) {
    case SCOPE: {
        enter_scope(node);
        analyze_body(node);
        exit_scope();
        break;
    }
    case TEMPLATE: {
        if (node->left == NULL)
            break;
        Node *insts = node->left;
        for (int i = 0; i < insts->children_count; i++) {
            Node *child = node->children[i];
            analyze(child, load);
        }
        break;
    }
    case VAL_CREATE: {
        // print("%n", node);
        node->left = analyze(node->left, 0);
        assert(node->left);
        break;
    }
    case LOAD: {
        node->left = analyze(node->left, 0);
        node->token->llvm.name = ura_text(node);
        // print("%n", node);
        // exit(1);

        return load ? node : node->left;
    }
    case NOT: {
        node->left = analyze(node->left, 1);
        if (analyze_type(node->left)->token->type != BOOL) {
            eprint("'not' needs a bool\n");
            exit(1);
        }
        node->token->llvm.name = ura_text(node);
        break;
    }
    case DECLARE: {
        Node *var = node->left;
        for (int i = 0; i < ura.scope->children_count; i++) {
            Node *child = ura.scope->children[i];
            if (child->token->type != DECLARE)
                continue;
            Node *dec = child->left;
            if (dec == var)
                break; // only the ones before it
            if (ura_cmp(dec->token->name, var->token->name)) {
                // x i32 = 2 again: suggest x = 2 (the type's token is on this line)
                Token *type = var->left->token;
                char *buff = curr_file()->token->file.buff;
                int after = type->e;
                while (buff[after] == ' ')
                    after++;
                bool assigns = type->line == var->token->line && buff[after] == '=';
                char *name = var->token->name;
                int line = dec->token->line + 1;
                char *msg = format("'%s' is already declared, on line %d", name, line);
                char *help = NULL;
                if (assigns)
                    help = fix_line(var->token->e, type->e - var->token->e, "");
                error((Error){
                    .token = var->token,
                    .msg = msg,
                    .help = help,
                });
                exit(1);
            }
        }
        var->token->type = VAR;
        var->token->llvm.name = var->token->name;
        break;
    }
    case STRUCT: {
        analyze_struct(node);
        enter_scope(node);
        analyze_body(node);
        exit_scope();
        break;
    } // clang-format off
    case VAR: case ARG: {
        node->token->llvm.name = node->token->name;
        break;
    } 
    case INIT_VAR: {
        break;
    }
    case ZERO: {
        break;
    }
    case I32: case I8: case BOOL: case CHARS: case VOID: {
        node->token->llvm.name = ura_text(node);
        break;
    } 
    case ARGS: { 
        break;
    }
    case DREF: {
        node->token->llvm.name = ura_text(node);
        break;
    }
    // clang-format on
    case REF: {
        // print(">>>>> %n", node);
        assert(node->left);
        node->left = analyze(node->left, 0);
        break;
    }
    case ARRAY_LIT: {
        // TODO: handle a i32[] = []
        analyze_body(node);
        if (node->children_count == 0)
            node->left = new_node(new_token(ANY, node->token));
        break;
    }
    case ID: {
        Node *to_find = find_variable(node->token->name);
        if (to_find == NULL) {
            undeclared_variable(node->token);
            exit(1);
        }

        Node *id = NULL;
        if (to_find->left && to_find->left->token->type == REF) {
            id = new_node(new_token(DREF, to_find->token));
            id->left = to_find;
            id->token->llvm.name = ura_text(id);
        } else
            id = to_find;

        if (load) {
            node = new_node(new_token(LOAD, node->token));
            node->left = id;
            node->token->llvm.name = ura_text(node);
        } else
            node = id;
        return node;
    }
    case ACCESS: {
        node->left = analyze(node->left, 1);
        assert(node->left != NULL);
        node->right = analyze(node->right, 1);
        assert(node->right != NULL);

        node->token->llvm.name = ura_text(node);
        break;
    }
    case DOT: {
        // print("%n\n", node->left);
        node->left = analyze(node->left, 1); // it can be LOAD->VAR->STRUCT or DOT
        assert(node->left != NULL);
        // TODO: assert VAR->STRUCT
        // Node *struct_node = type_of(node->left); // STRUCT
        char *src = node->left->token->name;
        Node *struct_node = analyze_type(node->left);
        if (struct_node->token->type == REF)
            struct_node = struct_node->left;

        // char *to_find = node->right->token->name;
        switch (node->right->token->type) {
        case ID: { // attribute
            // print("===================\n");
            // print("%n", node);
            // print("===================\n");
            Node *attr = node->right;
            node->right = find_attribute(node, struct_node, attr);
            if (node->right == NULL) {
                exit(1);
            }
            Node *right = node->right;
            node->token->llvm.name = ura_text(node);
            // attribute is a reference
            if (right->left->token->type == REF) {
                Node *dref = new_node(new_token(DREF, node->token));
                dref->left = node;
                dref->token->llvm.name = ura_text(dref);
                return dref;
            }
            return node;
        }
        case FN_CALL: { // method
            Node *method = node->right;
            Node *args = method->right;
            for (int i = 0; i < args->children_count; i++) {
                Node *child = args->children[i];
                args->children[i] = analyze(child, 1);
            }
            method->left = find_method(node->left, struct_node, method);
            if (method->left == NULL)
                exit(1);
            Type ret = method->left->left->token->type;
            char *name = ret != VOID ? ura_text(method) : "";
            method->token->llvm.name = name;
            return method;
            break;
        }
        default: {
            eprint("handle this case %k\n", node->right->token);
            exit(1);
        }
        }
        break;
    }
    case AS: {
        node->left = analyze(node->left, 1);
        node->token->llvm.name = ura_text(node);
        break;
    }
    case FN_CALL: {
        // TODO: recursive function might cause stack over flow
        // TODO: fcall_args_count != fdec_args_count
        Node *args = node->right;
        for (int i = 0; i < args->children_count; i++) {
            Node *child = args->children[i];
            args->children[i] = analyze(child, 1);
        }
        if (ura_cmp(node->token->name, "isNullable")) {
            if (args->children_count != 1) {
                eprint("isNullable takes one argument\n");
                exit(1);
            }
            Node *arg = args->children[0];
            if (arg->token->type == LOAD && arg->left->token->type == DREF)
                args->children[0] = arg->left;
            else if (analyze_type(arg)->token->type == STRUCT) {
                eprint("isNullable can't take a struct\n");
                exit(1);
            }
            node->token->llvm.name = ura_text(node); // before the type changes
            node->token->type = IS_NULLABLE;
            break;
        }
        node->left = find_function(node);
        char *name = node->left->left->token->type != VOID ? ura_text(node) : "";
        node->token->llvm.name = name;
        break;
    } // clang-format off
    case FN_DEC: case PROTO: { // clang-format on
        analyze_function(node);
        if (node->token->type != PROTO) {
            enter_scope(node);
            analyze_body(node);
            exit_scope();
        }
        break;
    }
    case IF: {
        // TODO: conidtion must be a boolean
        enter_scope(node);
        node->left = analyze(node->left, 1);
        analyze_body(node);
        Node *curr = node->right;
        while (curr) {
            if (curr->left)
                curr->left = analyze(curr->left, 1);
            analyze_body(curr);
            curr = curr->right;
        }
        exit_scope();
        break;
    }
    case WHILE: {
        enter_scope(node);
        node->left = analyze(node->left, 1);
        analyze_body(node);
        exit_scope();
        break;
    } // clang-format off
    case BRK: case CNT: break; // clang-format on
    case RETURN: {
        if (node->left)
            node->left = analyze(node->left, 1);
        break;
    }
    case ASSIGN: {
        // TODO: check compatibility
        node->left = analyze(node->left, 0);
        node->right = analyze(node->right, 1);
        // if (node->left->token->type == LOAD) // assign doesn't load left
        //     node->left = node->left->left;
        if (node->left->token->type == DREF && node->right->token->type == REF)
            node->left = node->left->left;
        // if (node->right->token->type == ARRAY_LIT && node->right->left &&
        //     node->right->left->token->type == ANY)
        //     node->right->left = node->left->left;
        break;
    } // clang-format off
    case AND: case OR: 
    case GT: case LT: case GE: case LE: case EQ: case NQ: 
    case ADD: case SUB: case MUL: case DIV: case MOD: {
        node->left = analyze(node->left, 1);
        assert(node->left);
        node->right = analyze(node->right, 1);
        assert(node->right);
        node->token->llvm.name = (char*)to_string(node->token->type);
        break;
    } 
    case ADD_ASSIGN: case SUB_ASSIGN: case MUL_ASSIGN:
    case DIV_ASSIGN: case MOD_ASSIGN: { // clang-format on
        node->left = analyze(node->left, 0);
        assert(node->left);
        node->right = analyze(node->right, 1);
        assert(node->right);
        node->token->llvm.name = (char *)to_string(node->token->type);
        break;
    }
    default: {
        eprint("handle this case %n\n", node);
        exit(1);
        break;
    }
    }
    return node;
}

